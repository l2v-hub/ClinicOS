import { chromium } from 'playwright';
const [OUT, MODE] = process.argv.slice(2);
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
await page.goto('http://127.0.0.1:5199');
await page.getByRole('button', { name: /Infermiere 1/ }).first().click();
await page.waitForSelector('.teams-sidebar');
await page.waitForTimeout(1200);
const side = (n) => page.locator('.teams-sidebar').getByRole('button', { name: n }).first().click();
await side(MODE === 'turno' ? 'Turno' : 'Pazienti');
await page.waitForTimeout(1500);
await page.getByText(MODE === 'turno' ? 'Nanni, Miriam' : 'Nanni').first().click();
await page.getByText('Nanni, Miriam').first().waitFor();
await page.waitForTimeout(2500);
await side('Consegne'); await page.waitForTimeout(5000);
const top = await page.evaluate(() => Math.round(document.querySelector('[data-chart-part="consegne"]')?.getBoundingClientRect().top ?? -1));
console.log(MODE, JSON.stringify({ firstVisitTop: top, vh: 820, inView: top >= 0 && top < 820 }));
await page.screenshot({ path: `${OUT}/QA-DL-Consegne-${MODE}.png` });
await b.close();
