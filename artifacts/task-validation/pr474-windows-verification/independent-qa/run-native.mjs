import { spawn, execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root = path.resolve(import.meta.dirname, '../../../..');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const source = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const files = execFileSync('git', ['ls-files', 'scripts/automation', 'agent-team/src/bug-pipeline', 'agent-team/tests/bug-pipeline', 'scripts/quality-gate'], { cwd: root, encoding: 'utf8' }).trim().split(/\r?\n/);
const snapshot = () => files.map(file => ({ file, sha256: hash(readFileSync(path.join(root, file))) }));
const before = snapshot();
const output = path.join(import.meta.dirname, `native-${Date.now()}`);
mkdirSync(output);
writeFileSync(path.join(output, 'source-before.json'), JSON.stringify(before, null, 2));
const temp = 'C:/Users/Claudio/.local/tmp/pr474-qa';
mkdirSync(temp, { recursive: true });
const env = { ...process.env, TEMP: temp, TMP: temp, PATH: process.env.PATH };
for (const key of Object.keys(env)) if (/TOKEN|API_KEY|SECRET|PASSWORD/i.test(key)) delete env[key];
const args = ['--test', '--test-concurrency=1', 'agent-team/tests/bug-pipeline/windows-review.test.mjs'];
const child = spawn(process.execPath, args, { cwd: root, env, windowsHide: true, shell: false });
let log = '';
child.stdout.on('data', bytes => { log += bytes; });
child.stderr.on('data', bytes => { log += bytes; });
const code = await new Promise((resolve, reject) => { child.once('error', reject); child.once('close', resolve); });
const after = snapshot();
assert.deepEqual(after, before, 'Application/test source changed during independent QA');
const counts = Object.fromEntries([...log.matchAll(/[ℹ#]\s+(tests|pass|fail|skipped|cancelled)\s+(\d+)/g)].map(match => [match[1], Number(match[2])]));
writeFileSync(path.join(output, 'source-after.json'), JSON.stringify(after, null, 2));
writeFileSync(path.join(output, 'test.log'), log);
const receipt = { source, code, args, counts, sourceUnchanged: true, manifestSha256: hash(JSON.stringify(before)), logSha256: hash(log), timestamp: new Date().toISOString() };
writeFileSync(path.join(output, 'receipt.json'), JSON.stringify(receipt, null, 2));
console.log(JSON.stringify({ output, ...receipt }));
console.log(log);
process.exitCode = code;
