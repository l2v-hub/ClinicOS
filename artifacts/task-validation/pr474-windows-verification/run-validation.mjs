import { spawn, execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const root=path.resolve(import.meta.dirname,'../../..');
const hash=b=>createHash('sha256').update(b).digest('hex');
const tracked=execFileSync('git',['ls-files','scripts/automation','agent-team/src/bug-pipeline','agent-team/tests/bug-pipeline','scripts/quality-gate'],{cwd:root,encoding:'utf8'}).trim().split(/\r?\n/);
const snapshot=()=>tracked.map(file=>({file,sha256:hash(readFileSync(path.join(root,file)))}));
const name=process.argv[2]||'native';
const out=path.join(import.meta.dirname,name+'-'+Date.now());mkdirSync(out);
const temp=path.join(os.homedir(),'.local/tmp/pr474-verification');
if(!existsSync(temp))mkdirSync(temp,{recursive:true});
const env={...process.env,TEMP:temp,TMP:temp,PATH:process.env.PATH};
for(const key of Object.keys(env))if(/TOKEN|API_KEY|SECRET|PASSWORD/i.test(key))delete env[key];
const tests=name==='native'?['agent-team/tests/bug-pipeline/windows-review.test.mjs']:[...readdirSync(path.join(root,'agent-team/tests/bug-pipeline')).filter(f=>f.endsWith('.test.mjs')).map(f=>'agent-team/tests/bug-pipeline/'+f),'scripts/quality-gate/claude-bug-review.test.mjs'];
for(const file of tests)assert.ok(existsSync(path.join(root,file)));
const before=snapshot();writeFileSync(path.join(out,'source-before.json'),JSON.stringify(before,null,2));
const args=['--test','--test-concurrency=1',...tests];
const child=spawn(process.execPath,args,{cwd:root,env,windowsHide:true,shell:false});let log='';child.stdout.on('data',b=>log+=b);child.stderr.on('data',b=>log+=b);
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve)});
const after=snapshot();assert.deepEqual(after,before);writeFileSync(path.join(out,'source-after.json'),JSON.stringify(after,null,2));
writeFileSync(path.join(out,'test.log'),log);const counts=Object.fromEntries([...log.matchAll(/[ℹ#]\s+(tests|pass|fail|skipped|cancelled)\s+(\d+)/g)].map(m=>[m[1],Number(m[2])]));
writeFileSync(path.join(out,'receipt.json'),JSON.stringify({code,args,counts,sourceSha256:hash(JSON.stringify(before)),sourceUnchanged:true,logSha256:hash(log),temp:'Explicit canonical synthetic test directory; avoids MSIX alias ambiguity',at:new Date().toISOString()},null,2));
console.log(JSON.stringify({out,code,counts}));console.log(log);process.exitCode=code;
